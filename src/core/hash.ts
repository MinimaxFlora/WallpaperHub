// FNV-1a 32-bit over UTF-16 code units. The deterministic selection modes
// depend on this output staying identical across runtimes and releases.
export function fnv1a(input: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}
